#!/usr/bin/env bash
# Verify the dwm/slock patch set and versions.
set -Eeuo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DWM="$ROOT/vendor/suckless/dwm"
SLOCK="$ROOT/vendor/suckless/slock"

grep -q '^VERSION = 6.8' "$DWM/config.mk" || { echo 'FAIL dwm not 6.8' >&2; exit 1; }
grep -q '^VERSION = 1.7' "$SLOCK/config.mk" || { echo 'FAIL slock not 1.7' >&2; exit 1; }

# status2d
grep -q 'drawstatusbar' "$DWM/dwm.c" || { echo 'FAIL status2d missing' >&2; exit 1; }
# statuscmd (nosignal)
grep -q 'StatusCmd' "$DWM/dwm.c" && grep -q 'statuscmdn' "$DWM/dwm.c" || { echo 'FAIL statuscmd missing' >&2; exit 1; }
grep -q 'statuscmds\[\]' "$DWM/config.h" || { echo 'FAIL statuscmds missing' >&2; exit 1; }
grep -q 'nirupi-status-click' "$DWM/config.h" || { echo 'FAIL status dispatcher missing' >&2; exit 1; }
# xresources
grep -q 'XResPref' "$DWM/dwm.c" && grep -q 'xresupdate' "$DWM/dwm.c" || { echo 'FAIL xresources missing' >&2; exit 1; }
grep -q 'resources\[\]' "$DWM/config.h" || { echo 'FAIL resources missing' >&2; exit 1; }
# 6.8 getatomprop regression fix
grep -q 'unsigned long nitems, dl;' "$DWM/dwm.c" || { echo 'FAIL getatomprop fix missing' >&2; exit 1; }
# config schema marker + compile-time guard
grep -q 'NIRUPI_CONFIG_VERSION' "$DWM/config.h" || { echo 'FAIL config marker missing' >&2; exit 1; }
grep -q 'NIRUPI_CONFIG_VERSION' "$DWM/dwm.c" || { echo 'FAIL config guard missing' >&2; exit 1; }
# statuscmd section ids must avoid whitespace control chars (tab/LF/VT/FF/CR)
ids=$(grep -oE 'nirupi-status-click\.sh [a-z]+", *[0-9]+' "$DWM/config.h" | grep -oE '[0-9]+$' | sort -n)
for id in $ids; do
  if [ "$id" -ge 9 ] && [ "$id" -le 13 ]; then echo "FAIL unsafe statuscmd id: $id" >&2; exit 1; fi
done
# every section id used by the script must exist in config.h statuscmds
cfg_ids=" $(grep -oE 'nirupi-status-click\.sh [a-z]+", *[0-9]+' "$DWM/config.h" | grep -oE '[0-9]+$' | sort -n | tr '\n' ' ') "
for id in $(grep -oE 'sect \([0-9]+\)' "$ROOT/vendor/noir/local/bin/dwm-status.sh" | grep -oE '[0-9]+' | sort -n | uniq); do
  case "$cfg_ids" in *" $id "*) ;; *) echo "FAIL sect id $id has no statuscmds entry" >&2; exit 1;; esac
done
# also the shell script must use the same ids (no 9..13)
if grep -oE 'sect ([0-9]+)' "$ROOT/vendor/noir/local/bin/dwm-status.sh" | grep -oE '[0-9]+' | awk '$1>=9 && $1<=13' | grep -q .; then
  echo 'FAIL dwm-status.sh uses an unsafe section id (9..13)' >&2; exit 1
fi

# slock 1.7 ctrl-u clear
grep -q "buf\[0\] == '\\\\025'" "$SLOCK/slock.c" || { echo 'FAIL slock ctrl-u fix missing' >&2; exit 1; }

# runtime colors for dwm are generated by the theme engine
grep -q 'dwm.background:' "$ROOT/lib/theme.sh" || { echo 'FAIL theme dwm colors missing' >&2; exit 1; }

# --- v0.6 bar/session patches -------------------------------------------------
# statusallmons: the bar draws the status on every monitor and updatestatus
# refreshes all bars.
grep -q 'm->statusw = m->ww - drawstatusbar' "$DWM/dwm.c" || { echo 'FAIL statusallmons draw missing' >&2; exit 1; }
grep -q 'statusallmons' "$DWM/dwm.c" || { echo 'FAIL statusallmons marker missing' >&2; exit 1; }
grep -A6 '^updatestatus' "$DWM/dwm.c" | grep -q 'drawbars();' || { echo 'FAIL statusallmons updatestatus missing' >&2; exit 1; }
# barpadding
grep -q 'vertpad' "$DWM/config.h" && grep -q 'sidepad' "$DWM/config.h" || { echo 'FAIL barpadding config missing' >&2; exit 1; }
grep -q 'm->ww = m->mw - 2 \* sidepad' "$DWM/dwm.c" || { echo 'FAIL barpadding geometry missing' >&2; exit 1; }
# tagicons
grep -q 'tagicons\[\]' "$DWM/config.h" || { echo 'FAIL tagicons array missing' >&2; exit 1; }
grep -q 'tagtext' "$DWM/dwm.c" || { echo 'FAIL tagicons helper missing' >&2; exit 1; }
# focusurgent
grep -q 'focusurgent(const Arg' "$DWM/dwm.c" || { echo 'FAIL focusurgent missing' >&2; exit 1; }
grep -q 'focusurgent,' "$DWM/config.h" || { echo 'FAIL focusurgent binding missing' >&2; exit 1; }
# actualfullscreen
grep -q 'togglefullscr(const Arg' "$DWM/dwm.c" || { echo 'FAIL actualfullscreen missing' >&2; exit 1; }
grep -q 'togglefullscr,' "$DWM/config.h" || { echo 'FAIL actualfullscreen binding missing' >&2; exit 1; }
grep -q 'isfullscreen' "$DWM/config.h" || { echo 'FAIL fullscreen rule field missing' >&2; exit 1; }
# cyclelayouts (with trailing sentinel)
grep -q 'cyclelayout(const Arg' "$DWM/dwm.c" || { echo 'FAIL cyclelayout missing' >&2; exit 1; }
grep -q 'cyclelayout,' "$DWM/config.h" || { echo 'FAIL cyclelayout binding missing' >&2; exit 1; }
grep -q '{ NULL, *NULL }' "$DWM/config.h" || { echo 'FAIL cyclelayouts sentinel missing' >&2; exit 1; }
# swallow
grep -q 'swallow(Client' "$DWM/dwm.c" && grep -q 'unswallow(Client' "$DWM/dwm.c" || { echo 'FAIL swallow missing' >&2; exit 1; }
grep -q 'isterminal' "$DWM/config.h" || { echo 'FAIL swallow rule fields missing' >&2; exit 1; }
grep -q 'name "scratchpad".*kitty\|scratchpad' "$DWM/config.h" || { echo 'FAIL swallow terminal rules missing' >&2; exit 1; }
grep -q 'xcb_res_query_client_ids' "$DWM/dwm.c" || { echo 'FAIL swallow winpid missing' >&2; exit 1; }
grep -q 'lX11-xcb' "$DWM/config.mk" && grep -q 'lX11-xcb' "$DWM/config.mk" || { echo 'FAIL swallow link libs missing' >&2; exit 1; }
grep -q 'lxcb-res' "$DWM/config.mk" || { echo 'FAIL xcb-res link missing' >&2; exit 1; }
# the new bar commands/ids must stay collision-free (also asserted by keybindings.sh)
echo 'PASS: dwm 6.8 + status2d/statuscmd/xresources, bar patches (statusallmons/barpadding/tagicons), swallow, actualfullscreen, focusurgent, cyclelayouts, slock 1.7'
